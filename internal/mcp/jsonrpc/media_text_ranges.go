// mediaTextRanges holds the scalar values a decoded media view keeps as text.
// It is a closed set on purpose. Decoding arbitrary binary as UTF-16 yields
// mostly printable CJK, so keeping "anything printable" makes every benign
// image emit text about as large as itself. A scalar belongs here only when a
// scanner pattern can still match it, or a character it normalizes to, after
// the scanner's own normalization:
//
//   - printable ASCII, the Latin-1 supplement and Latin Extended-A/B, and the
//     General Punctuation block (the dashes and quotes the response patterns
//     name, and NFKC's source for ASCII punctuation);
//   - every scalar internal/normalize turns into printable ASCII under
//     ForMatching, ForDLP or ForToolText: the Greek, Cyrillic, Armenian and
//     Cherokee homoglyphs of confusableMap (internal/normalize/normalize.go),
//     the small-capital and phonetic letters, the NFKC sources (fullwidth and
//     small forms, letterlike symbols, enclosed alphanumerics, ligatures,
//     mathematical alphanumerics, squared and regional-indicator letters).
//
// Scalars the scanner deletes outright (C0 and C1 controls, normalize.
// InvisibleRanges, combining marks) are not listed: they are transparent to a
// run, see mediaRuneClass. TestMediaTextRangesCoverNormalizer recomputes the
// derived part from the normalizer over every scalar and fails when the
// normalizer begins mapping a scalar to ASCII that this table omits, so the
// table cannot drift from the scanner silently.
//
// Deliberately absent: CJK ideographs, Hangul syllables, kana and every other
// scalar no normalization stage folds toward ASCII. The default CJK patterns
// can still match those scripts as plain text, but a UTF-16 reading of random
// bytes is mostly in those blocks, and keeping them would again turn ordinary
// image bytes into scanned text. Text in those scripts hidden in a media
