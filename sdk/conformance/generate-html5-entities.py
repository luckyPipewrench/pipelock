"""Generate v5 HTML5 tables and byte-parity vectors from pinned WHATWG data."""

import argparse
import base64
import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "sdk/conformance/testdata/html5/entities.json"
SOURCE_SHA256 = "d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6"


def generate() -> dict[Path, str]:
    raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("WHATWG entities.json differs from its pinned SHA-256")
    table = {}
    for name, entity in sorted(json.loads(raw).items()):
        assert name.startswith("&") and name[1:].rstrip(";").isalnum()
        assert entity["characters"] == "".join(map(chr, entity["codepoints"]))
        table[name] = entity["characters"]
    longest = max(map(len, table))

    def decode(value: str) -> tuple[str, int]:
        # Independent text-state oracle: longest match at each original
        # ampersand. Never rescan output within the same charged pass.
        processed = len(value.encode())  # Recipe operation input.
        if "&" not in value:
            return value, processed
        for _ in range(16):
            processed += len(value.encode())
            out = []
            pos = 0
            while pos < len(value):
                if value[pos] == "&":
                    for end in range(min(len(value), pos + longest), pos + 1, -1):
                        reference = value[pos:end]
                        if reference in table:
                            out.append(table[reference])
                            pos = end
                            break
                    else:
                        out.append(value[pos])
                        pos += 1
                else:
                    out.append(value[pos])
                    pos += 1
            decoded = "".join(out)
            if decoded == value:
                break
            value = decoded
        return value, processed

    inputs = set(table)
    inputs.update(name[:-1] for name in table if name.endswith(";"))
    legacy_cases = set()
    for name in table:
        if not name.endswith(";"):
            for suffix in ("it;", "=", "=tail", "x", "0", "!", "é"):
                legacy_cases.add(name + suffix)
    inputs.update(legacy_cases)
    inputs.update("&amp;" + name[1:] for name in table)
    inputs.update(("&", "&;", "&unknown;", "&NotEqualTilde", "&amp;&lt;"))
    parity = {
        "source_sha256": SOURCE_SHA256,
        "vectors": [{"input": v, "output": decode(v)[0]} for v in sorted(inputs)],
    }

    def rust_string(value: str) -> str:
        # Expose both scalars, including invisible variation selectors.
        return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in value) + '"'

    rust = (
        "// Copyright 2026 Pipelock contributors\n"
        "// SPDX-License-Identifier: Apache-2.0\n\n"
        "// Code generated by sdk/conformance/generate-html5-entities.py; DO NOT EDIT.\n"
        f"// WHATWG entities.json SHA-256: {SOURCE_SHA256}\n"
        f"pub(crate) const MAX_NAME_BYTES: usize = {longest - 1};\n"
        "pub(crate) const NAMED: &[(&str, &str)] = &[\n"
    )
    rust += "".join(
        f"    ({json.dumps(name[1:])}, {rust_string(value)}),\n"
        for name, value in table.items()
    )
    rust += "];\n"

    go = (
        "// Copyright 2026 Pipelock contributors\n"
        "// SPDX-License-Identifier: Apache-2.0\n\n"
        "// Code generated by sdk/conformance/generate-html5-entities.py; DO NOT EDIT.\n"
        f"// WHATWG entities.json SHA-256: {SOURCE_SHA256}\n\n"
        "package normalize\n\n"
        f"const html5MaxNameBytes = {longest - 1}\n\n"
        "var html5NamedReferences = map[string]string{\n"
    )
    for name, value in table.items():
        escaped = "".join(
            f"\\u{ord(c):04x}" if ord(c) <= 0xFFFF else f"\\U{ord(c):08x}"
            for c in value
        )
        go += f'\t{json.dumps(name[1:])}: "{escaped}",\n'
    go += "}\n"
    go = subprocess.run(
        ["gofmt"], input=go, text=True, capture_output=True, check=True
    ).stdout

    corpus_path = (
        ROOT / "sdk/conformance/testdata/transform-profile/evidence-provenance-v5.json"
    )
    corpus = json.loads(corpus_path.read_text())
    corpus["vectors"] = [
        v for v in corpus["vectors"] if not v["id"].startswith("html5-generated-")
    ]
    # Every multi-scalar entity and legacy spelling/prefix also runs in the
    # ordinary v5 replay corpus, independently of the exhaustive table test.
    selected = set(legacy_cases)
    selected.update(
        name
        for name, value in table.items()
        if len(value) > 1 or not name.endswith(";")
    )
    selected.update(
        name[:-1]
        for name in table
        if name.endswith(";") and decode(name[:-1])[0] != name[:-1]
    )
    selected.update(
        "&amp;" + name[1:]
        for name, value in table.items()
        if len(value) > 1 or not name.endswith(";")
    )
    for value in sorted(selected):
        corpus["vectors"].append(
            {
                "id": "html5-generated-" + value,
                "input_b64": base64.b64encode(value.encode()).decode(),
                "recipe": [{"kind": "html_entity_decode"}],
                "output_b64": base64.b64encode(decode(value)[0].encode()).decode(),
                "processed_bytes": decode(value)[1],
            }
        )
    return {
        ROOT / "internal/normalize/html5_entities_v5.go": go,
        ROOT / "sdk/verifiers/rust/src/html5_entities_v5.rs": rust,
        ROOT / "sdk/conformance/testdata/html5/parity-v5.json": json.dumps(
            parity, ensure_ascii=True, indent=2
        )
        + "\n",
        corpus_path: json.dumps(corpus, ensure_ascii=True, indent=2) + "\n",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(
                    f"stale generated HTML5 artifact: {path.relative_to(ROOT)}"
                )
        else:
            path.write_text(content)
    print("PASS: pinned WHATWG table and generated v5 artifacts")


if __name__ == "__main__":
    main()
