package conformance

import (
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"unicode"

	"github.com/luckyPipewrench/pipelock/internal/jsonscan"
)

// Go's Unicode simple-fold cycles define JSON key identity. Generate the port
// tables from that authority; native lowercase/full casefold have different
// equivalence classes. Regenerate with PIPELOCK_KEY_FOLD_TABLES=1.
func TestJSONKeyFoldTables(t *testing.T) {
	groups := []string{}
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if unicode.SimpleFold(r) == r || jsonscan.FoldKey(string(r)) != string(r) {
			continue
		}
		group := string(r)
		for next := unicode.SimpleFold(r); next != r; next = unicode.SimpleFold(next) {
			group += string(next)
		}
		groups = append(groups, group)
	}
	var rows []string
	for i := 0; i < len(groups); i += 16 {
		end := min(i+16, len(groups))
		rows = append(rows, strings.Join(groups[i:end], " "))
	}
	table := strings.Join(rows, "\n")
	version := "Unicode " + unicode.Version + " simple-fold cycles; generated by TestJSONKeyFoldTables."
	files := map[string]string{
		"../verifiers/ts/src/key-fold-data.ts":                          "// " + version + "\n// SPDX-License-Identifier: Apache-2.0\n\nexport const KEY_FOLD_GROUPS = `" + table + "`;\n",
		"../verifiers/python/src/pipelock_aarp_verify/key_fold_data.py": "# " + version + "\n# SPDX-License-Identifier: Apache-2.0\n\nKEY_FOLD_GROUPS = \"\"\"" + table + "\"\"\"\n",
		"../verifiers/rust/src/key_fold_data.rs":                        "// " + version + "\n// SPDX-License-Identifier: Apache-2.0\n\npub(crate) const KEY_FOLD_GROUPS: &str = r\"" + table + "\";\n",
	}
	for path, want := range files {
		if os.Getenv("PIPELOCK_KEY_FOLD_TABLES") == "1" {
			if err := os.WriteFile(filepath.Clean(path), []byte(want), 0o600); err != nil {
				t.Fatal(err)
			}
		}
		got, err := os.ReadFile(filepath.Clean(path))
		if err != nil {
			t.Fatal(err)
		}
		if string(got) != want {
			t.Errorf("%s differs from Go simple-fold table", path)
		}
	}
	path := "testdata/json-key-folding.json"
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var fixture struct {
		Cases []struct {
			Name  string `json:"name"`
			Raw   string `json:"raw"`
			Valid bool   `json:"valid"`
		} `json:"cases"`
		Groups []string `json:"groups"`
	}
	if err := json.Unmarshal(data, &fixture); err != nil {
		t.Fatal(err)
	}
	if os.Getenv("PIPELOCK_KEY_FOLD_TABLES") == "1" {
		fixture.Groups = groups
		raw, err := json.MarshalIndent(fixture, "", "  ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, append(raw, '\n'), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	if strings.Join(fixture.Groups, " ") != strings.Join(groups, " ") {
		t.Fatal("shared fixture differs from Go simple-fold cycles")
	}
}
